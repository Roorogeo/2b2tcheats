package dev.noir.basehunt;

import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/** Block id groups used by the base-hunting checks. */
public final class Blocks {
    private Blocks() {}

    public static final List<String> COLORS = List.of("white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray",
        "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black");
    public static final List<String> WOODS = List.of("oak", "spruce", "birch", "jungle", "acacia", "dark_oak", "mangrove", "cherry",
        "pale_oak", "bamboo", "crimson", "warped");

    public static final Set<String> AIR = Set.of("minecraft:air", "minecraft:cave_air", "minecraft:void_air");

    public static final Set<String> STORAGE;
    public static final Set<String> SHULKERS;
    public static final Set<String> PORTALS = Set.of("minecraft:nether_portal", "minecraft:end_portal", "minecraft:end_gateway");

    /** Natural stone that ore veins replace; exposed faces of these show mined areas. */
    public static final Set<String> HOST_STONE = Set.of("minecraft:stone", "minecraft:deepslate", "minecraft:andesite",
        "minecraft:diorite", "minecraft:granite", "minecraft:tuff", "minecraft:netherrack");

    /** Blocks that only exist in chunks generated by 1.16+ (nether) / 1.18+ (overworld below y 0). */
    public static final Set<String> NETHER_116 = Set.of("minecraft:basalt", "minecraft:blackstone", "minecraft:crimson_nylium",
        "minecraft:warped_nylium", "minecraft:soul_soil", "minecraft:ancient_debris", "minecraft:crimson_stem", "minecraft:warped_stem",
        "minecraft:nether_gold_ore");
    public static final Set<String> OVERWORLD_118 = Set.of("minecraft:deepslate", "minecraft:tuff", "minecraft:deepslate_iron_ore",
        "minecraft:deepslate_coal_ore", "minecraft:deepslate_redstone_ore");

    static {
        List<String> shulkers = new ArrayList<>();
        shulkers.add("minecraft:shulker_box");
        for (String c : COLORS) shulkers.add("minecraft:" + c + "_shulker_box");
        SHULKERS = Set.copyOf(shulkers);
        List<String> storage = new ArrayList<>(shulkers);
        storage.addAll(List.of("minecraft:chest", "minecraft:trapped_chest", "minecraft:barrel", "minecraft:ender_chest",
            "minecraft:hopper", "minecraft:dropper", "minecraft:dispenser", "minecraft:copper_chest"));
        STORAGE = Set.copyOf(storage);
    }

    public static boolean isAir(String id) {
        return id == null || AIR.contains(id);
    }

    public static boolean isOre(String id) {
        return id.endsWith("_ore") || id.equals("minecraft:ancient_debris");
    }

    /** Default list for SusChunk's player-placed check. */
    public static String[] defaultPlacedBlocks() {
        List<String> ids = new ArrayList<>(List.of("obsidian", "crying_obsidian", "ender_chest", "crafting_table", "furnace",
            "blast_furnace", "smoker", "anvil", "enchanting_table", "brewing_stand", "beacon", "respawn_anchor", "rail", "powered_rail",
            "detector_rail", "activator_rail", "glass", "glass_pane", "netherite_block", "diamond_block", "iron_block", "gold_block"));
        for (String c : COLORS) {
            ids.add(c + "_bed");
            ids.add(c + "_wool");
            ids.add(c + "_stained_glass");
            ids.add(c + "_shulker_box");
        }
        ids.add("shulker_box");
        for (String w : WOODS) {
            ids.add(w + "_sign");
            ids.add(w + "_wall_sign");
        }
        return ids.toArray(String[]::new);
    }
}
